#ifndef BL_PROTOCOL_H
#define BL_PROTOCOL_H

#include <stdbool.h>
#include <stdint.h>

#include "bl_packet.h"

/*
 * Bootloader protocol command identifiers.
 */
typedef uint8_t BL_Command_t;

/*
 * Bootloader response identifiers.
 */
typedef uint8_t BL_ResponseCommand_t;

/*
 * Action requested by a successfully processed command.
 *
 * The action must be executed only after the response packet
 * has been transmitted to the host.
 */
typedef enum
{
    BL_COMMAND_ACTION_NONE = 0,
    BL_COMMAND_ACTION_RUN_APP,
    BL_COMMAND_ACTION_RESET
} BL_CommandAction_t;

/*
 * Bootloader version.
 *
 * Encoded as:
 *
 *   bits 31..24 = major
 *   bits 23..16 = minor
 *   bits 15.. 0 = patch
 */
#define BL_BOOTLOADER_VERSION_MAJOR    (1U)
#define BL_BOOTLOADER_VERSION_MINOR    (0U)
#define BL_BOOTLOADER_VERSION_PATCH    (0U)

#define BL_BOOTLOADER_VERSION \
    (((uint32_t)BL_BOOTLOADER_VERSION_MAJOR << 24U) | \
     ((uint32_t)BL_BOOTLOADER_VERSION_MINOR << 16U) | \
     ((uint32_t)BL_BOOTLOADER_VERSION_PATCH))

/*
 * Capability bits returned by GET_INFO.
 */
#define BL_CAPABILITY_RS232    (1UL << 0U)
#define BL_CAPABILITY_RS485    (1UL << 1U)
#define BL_CAPABILITY_SPI      (1UL << 2U)
#define BL_CAPABILITY_I2C      (1UL << 3U)
#define BL_CAPABILITY_ETHERNET (1UL << 4U)

/*
 * GET_INFO response.
 *
 * Total size: 24 bytes.
 */
typedef struct
{
    uint32_t bootloaderVersion;
    uint32_t flashStart;
    uint32_t flashSize;
    uint32_t applicationStart;
    uint32_t applicationMaxSize;
    uint32_t capabilities;
} BL_InfoResponse_t;

/*
 * Initialize the protocol layer.
 *
 * This clears duplicate-response state and initializes
 * the expected packet sequence.
 */
void BL_ProtocolInit(void);

/*
 * Process one decoded request packet.
 *
 * Parameters:
 *   request  - decoded request packet
 *   response - response packet generated by the protocol
 *   action   - action that the bootloader must execute after
 *              transmitting the response
 *
 * Returns:
 *   true  - response successfully generated
 *   false - invalid arguments/internal response generation failure
 *
 * Important:
 *
 * RUN_APP and RESET do NOT execute inside this function.
 * They only set *action.
 */
bool BL_ProtocolProcessPacket(
    const BL_Packet_t *request,
    BL_Packet_t *response,
    BL_CommandAction_t *action);

#endif /* BL_PROTOCOL_H */
